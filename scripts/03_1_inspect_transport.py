#!/usr/bin/env python3
"""
Inspection and quality control of transport maps
generated by Waddington-OT.

This script DOES NOT modify the transport maps.

For each transition:
    D0 -> D2
    D2 -> D5
    D5 -> D9

the following are evaluated:

1. Matrix dimensions.
2. Source and destination cell names.
3. NaN/Inf values.
4. Negative values.
5. Total transported mass.
6. Mass exiting each cell.
7. Mass entering each cell.
8. Input/output mass statistics.
9. Statistics of non-zero transport weights.
10. Number of non-zero connections.
11. Cells with extremely concentrated or diffuse transport.

"""

from pathlib import Path

import numpy as np
import pandas as pd
import scanpy as sc


# ============================================================
# CONFIGURATION
# ============================================================

BASE_DIR = Path(".")

WOT_DIR = BASE_DIR / "results" / "wot"
INSPECTION_DIR = WOT_DIR / "inspection"

INSPECTION_DIR.mkdir(parents=True, exist_ok=True)

TRANSPORT_MAPS = {
    "0_2": WOT_DIR / "tmap_leishmania_0_2.h5ad",
    "2_5": WOT_DIR / "tmap_leishmania_2_5.h5ad",
    "5_9": WOT_DIR / "tmap_leishmania_5_9.h5ad",
}


# ============================================================
# FUNCTIONS
# ============================================================

def inspect_transport_map(path, transition):

    print("\n" + "=" * 70)
    print(f"TRANSITION: {transition}")
    print(f"FILE: {path.name}")
    print("=" * 70)

    if not path.exists():
        raise FileNotFoundError(
            f"Transport map not found: {path}"
        )

    # --------------------------------------------------------
    # Load map
    # --------------------------------------------------------

    tmap = sc.read_h5ad(path)

    print(f"Shape: {tmap.shape}")
    print(f"Source cells: {tmap.n_obs}")
    print(f"Target cells: {tmap.n_vars}")

    # --------------------------------------------------------
    # Structure
    # --------------------------------------------------------

    print("\nStructure:")
    print(f"  obs columns: {list(tmap.obs.columns)}")
    print(f"  var columns: {list(tmap.var.columns)}")

    print("\nFirst source cells:")
    print(list(tmap.obs_names[:5]))

    print("\nFirst target cells:")
    print(list(tmap.var_names[:5]))

    # --------------------------------------------------------
    # Matrix
    # --------------------------------------------------------

    X = tmap.X

    print(f"\nMatrix type: {type(X)}")

    # --------------------------------------------------------
    # Determine matrix representation
    # --------------------------------------------------------

    if isinstance(X, np.ndarray):

        print("Representation: dense NumPy array")

        n_total = X.size

        # Avoid creating another full copy.
        values = X.ravel()

        n_nonzero = np.count_nonzero(values)

        n_nan = np.isnan(values).sum()
        n_inf = np.isinf(values).sum()
        n_negative = np.count_nonzero(values < 0)

        print("\nMatrix statistics:")
        print(f"  Total entries:  {n_total:,}")
        print(f"  Non-zero:       {n_nonzero:,}")
        print(
            f"  Density:        "
            f"{n_nonzero / n_total:.6e}"
        )
        print(
            f"  Sparsity:       "
            f"{1 - n_nonzero / n_total:.6f}"
        )

        print(f"  NaN values:     {n_nan:,}")
        print(f"  Inf values:     {n_inf:,}")
        print(f"  Negative:       {n_negative:,}")

        # ----------------------------------------------------
        # Non-zero statistics
        # ----------------------------------------------------

        nonzero_values = values[values != 0]

        if nonzero_values.size > 0:

            print("\nNon-zero transport weight statistics:")

            print(
                f"  Minimum: "
                f"{nonzero_values.min():.6e}"
            )

            print(
                f"  Maximum: "
                f"{nonzero_values.max():.6e}"
            )

            print(
                f"  Mean:    "
                f"{nonzero_values.mean():.6e}"
            )

            print(
                f"  Median:  "
                f"{np.median(nonzero_values):.6e}"
            )

            print(
                f"  1st pct: "
                f"{np.percentile(nonzero_values, 1):.6e}"
            )

            print(
                f"  99th pct:"
                f" {np.percentile(nonzero_values, 99):.6e}"
            )

    else:

        print("Representation: sparse matrix")

        n_total = X.shape[0] * X.shape[1]

        values = X.data

        n_nonzero = values.size

        n_nan = np.isnan(values).sum()
        n_inf = np.isinf(values).sum()
        n_negative = np.count_nonzero(values < 0)

        print("\nMatrix statistics:")
        print(f"  Total entries:  {n_total:,}")
        print(f"  Non-zero:       {n_nonzero:,}")
        print(
            f"  Density:        "
            f"{n_nonzero / n_total:.6e}"
        )
        print(
            f"  Sparsity:       "
            f"{1 - n_nonzero / n_total:.6f}"
        )

        print(f"  NaN values:     {n_nan:,}")
        print(f"  Inf values:     {n_inf:,}")
        print(f"  Negative:       {n_negative:,}")

        if values.size > 0:

            print("\nNon-zero transport weight statistics:")

            print(
                f"  Minimum: "
                f"{values.min():.6e}"
            )

            print(
                f"  Maximum: "
                f"{values.max():.6e}"
            )

            print(
                f"  Mean:    "
                f"{values.mean():.6e}"
            )

            print(
                f"  Median:  "
                f"{np.median(values):.6e}"
            )

            print(
                f"  1st pct: "
                f"{np.percentile(values, 1):.6e}"
            )

            print(
                f"  99th pct:"
                f" {np.percentile(values, 99):.6e}"
            )

    # --------------------------------------------------------
    # Mass leaving each source cell
    # --------------------------------------------------------

    mass_out = np.asarray(
        X.sum(axis=1)
    ).ravel()

    # --------------------------------------------------------
    # Mass arriving at each target cell
    # --------------------------------------------------------

    mass_in = np.asarray(
        X.sum(axis=0)
    ).ravel()

    # --------------------------------------------------------
    # Mass statistics
    # --------------------------------------------------------

    print("\nMass leaving source cells:")

    print(
        f"  Total mass: "
        f"{mass_out.sum():.6e}"
    )

    print(
        f"  Minimum:    "
        f"{mass_out.min():.6e}"
    )

    print(
        f"  Maximum:    "
        f"{mass_out.max():.6e}"
    )

    print(
        f"  Mean:       "
        f"{mass_out.mean():.6e}"
    )

    print(
        f"  Median:     "
        f"{np.median(mass_out):.6e}"
    )

    print(
        f"  1st pct:    "
        f"{np.percentile(mass_out, 1):.6e}"
    )

    print(
        f"  99th pct:   "
        f"{np.percentile(mass_out, 99):.6e}"
    )

    print("\nMass arriving at target cells:")

    print(
        f"  Total mass: "
        f"{mass_in.sum():.6e}"
    )

    print(
        f"  Minimum:    "
        f"{mass_in.min():.6e}"
    )

    print(
        f"  Maximum:    "
        f"{mass_in.max():.6e}"
    )

    print(
        f"  Mean:       "
        f"{mass_in.mean():.6e}"
    )

    print(
        f"  Median:     "
        f"{np.median(mass_in):.6e}"
    )

    print(
        f"  1st pct:    "
        f"{np.percentile(mass_in, 1):.6e}"
    )

    print(
        f"  99th pct:   "
        f"{np.percentile(mass_in, 99):.6e}"
    )

    # --------------------------------------------------------
    # Number of connections
    # --------------------------------------------------------

    n_connections_out = np.count_nonzero(
        X,
        axis=1
    )

    n_connections_in = np.count_nonzero(
        X,
        axis=0
    )

    print("\nConnections per source cell:")

    print(
        f"  Minimum: "
        f"{n_connections_out.min()}"
    )

    print(
        f"  Maximum: "
        f"{n_connections_out.max()}"
    )

    print(
        f"  Mean:    "
        f"{n_connections_out.mean():.2f}"
    )

    print(
        f"  Median:  "
        f"{np.median(n_connections_out):.0f}"
    )

    print("\nConnections per target cell:")

    print(
        f"  Minimum: "
        f"{n_connections_in.min()}"
    )

    print(
        f"  Maximum: "
        f"{n_connections_in.max()}"
    )

    print(
        f"  Mean:    "
        f"{n_connections_in.mean():.2f}"
    )

    print(
        f"  Median:  "
        f"{np.median(n_connections_in):.0f}"
    )

    # --------------------------------------------------------
    # Save source-level information
    # --------------------------------------------------------

    source_df = pd.DataFrame(
        {
            "cell_id": tmap.obs_names,
            "mass_out": mass_out,
            "n_connections": n_connections_out,
        }
    )

    source_output = (
        INSPECTION_DIR
        / f"transport_source_{transition}.csv"
    )

    source_df.to_csv(
        source_output,
        index=False
    )

    # --------------------------------------------------------
    # Save target-level information
    # --------------------------------------------------------

    target_df = pd.DataFrame(
        {
            "cell_id": tmap.var_names,
            "mass_in": mass_in,
            "n_connections": n_connections_in,
        }
    )

    target_output = (
        INSPECTION_DIR
        / f"transport_target_{transition}.csv"
    )

    target_df.to_csv(
        target_output,
        index=False
    )

    # --------------------------------------------------------
    # Summary
    # --------------------------------------------------------

    summary = {
        "transition": transition,
        "n_source_cells": tmap.n_obs,
        "n_target_cells": tmap.n_vars,
        "total_entries": n_total,
        "nonzero_entries": n_nonzero,
        "density": n_nonzero / n_total,
        "sparsity": 1 - n_nonzero / n_total,
        "total_mass_out": mass_out.sum(),
        "total_mass_in": mass_in.sum(),
        "min_mass_out": mass_out.min(),
        "max_mass_out": mass_out.max(),
        "median_mass_out": np.median(mass_out),
        "min_mass_in": mass_in.min(),
        "max_mass_in": mass_in.max(),
        "median_mass_in": np.median(mass_in),
        "nan_values": n_nan,
        "inf_values": n_inf,
        "negative_values": n_negative,
    }

    return summary


# ============================================================
# MAIN
# ============================================================

def main():

    print("\nWADDINGTON-OT TRANSPORT MAP INSPECTION")
    print("=" * 70)

    summaries = []

    for transition, path in TRANSPORT_MAPS.items():

        summary = inspect_transport_map(
            path=path,
            transition=transition,
        )

        summaries.append(summary)

    # --------------------------------------------------------
    # Save summary
    # --------------------------------------------------------

    summary_df = pd.DataFrame(
        summaries
    )

    summary_output = (
        INSPECTION_DIR
        / "transport_summary.csv"
    )

    summary_df.to_csv(
        summary_output,
        index=False
    )

    print("\n" + "=" * 70)
    print("INSPECTION COMPLETE")
    print("=" * 70)

    print(
        f"\nSummary saved to:\n"
        f"{summary_output}"
    )

    print(
        "\nSource-level results saved to:\n"
        f"{INSPECTION_DIR}/transport_source_*.csv"
    )

    print(
        "\nTarget-level results saved to:\n"
        f"{INSPECTION_DIR}/transport_target_*.csv"
    )


if __name__ == "__main__":
    main()